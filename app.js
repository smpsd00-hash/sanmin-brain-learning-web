const $ = s => document.querySelector(s);
const $$ = s => [...document.querySelectorAll(s)];

function esc(str){
  return String(str).replace(/[&<>"]/g, m => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[m]));
}
function list(items){ return `<ul>${items.map(x=>`<li>${esc(x)}</li>`).join('')}</ul>`; }
function p(text){ return `<p>${esc(text)}</p>`; }

function renderMap(){
  const table = $('#curriculumTable');
  const headers=['年級','發展階段','記憶的秘密','睡眠與大腦','注意力管理','壓力與情緒','教師焦點'];
  const rows=[];
  for(let g=1; g<=6; g++){
    const c=CURRICULUM[g];
    const coreGrade = g<=2?1:(g<=4?3:(g===5?5:6));
    const mapLessons = LESSONS.filter(x=>x.grade===coreGrade);
    rows.push(`<tr><td><span class="grade-badge">${g} 年級</span></td><td><div class="map-main">${esc(c.stage)}</div><div class="map-sub">${esc(c.stageHint)}</div></td>`+
      mapLessons.map(x=>`<td><div class="map-main">${esc(x.title)}</div><div class="map-sub">${esc(x.tagline)}</div><button class="unit-link" data-open="${x.id}">查看教案 →</button></td>`).join('')+
      `<td><div class="map-sub">${g===1?'先體驗、先命名。':g===2?'增加理由與選擇。':g===3?'比較方法、開始記錄。':g===4?'用證據解釋策略。':g===5?'自主設定與修正。':'整合策略、準備升國中。'}</div></td></tr>`);
  }
  table.innerHTML=`<thead><tr>${headers.map(h=>`<th>${h}</th>`).join('')}</tr></thead><tbody>${rows.join('')}</tbody>`;
}

function renderLessons(filter={grade:'all',theme:'all'}){
  const grid=$('#lessonGrid');
  const data=LESSONS.filter(x => (filter.grade==='all'||String(x.grade)===String(filter.grade)) && (filter.theme==='all'||x.theme===filter.theme));
  grid.innerHTML=data.map(x=>{
    const t=THEME[x.theme];
    return `<article class="lesson-card" data-grade="${x.grade}" data-theme="${x.theme}">
      <div class="lesson-top"><span class="lesson-number">${x.band}</span><span class="theme-label ${t.cls}">${t.label}</span></div>
      <h3>${esc(x.title)}</h3><p>${esc(x.tagline)}</p>
      <div class="badge-row"><span class="mini-badge">${esc(x.duration)}</span><span class="mini-badge">目標 ×3</span><span class="mini-badge">學習單</span></div>
      <div class="lesson-footer"><span class="duration">核心主題：${esc(x.themeName)}</span><button class="open-lesson" data-open="${x.id}">開啟教案</button></div>
    </article>`;
  }).join('') || `<div class="info-card" style="grid-column:1/-1">目前沒有符合條件的單元。</div>`;
}

